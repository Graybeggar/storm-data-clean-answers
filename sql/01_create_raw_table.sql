-- Storm Data, Clean Answers
-- Step 1: raw landing table. Every column is TEXT, exactly as NOAA published it.
-- Source: NOAA/NCEI Storm Events Database, "details" files, 2021-2024,
-- filtered to STATE in ('IOWA', 'PENNSYLVANIA'). 15,100 rows.

DROP TABLE IF EXISTS storm_events_raw;

CREATE TABLE storm_events_raw (
    BEGIN_YEARMONTH   TEXT,
    BEGIN_DAY         TEXT,
    BEGIN_TIME        TEXT,
    END_YEARMONTH     TEXT,
    END_DAY           TEXT,
    END_TIME          TEXT,
    EPISODE_ID        TEXT,
    EVENT_ID          TEXT,
    STATE             TEXT,
    STATE_FIPS        TEXT,
    YEAR              TEXT,
    MONTH_NAME        TEXT,
    EVENT_TYPE        TEXT,
    CZ_TYPE           TEXT,
    CZ_FIPS           TEXT,
    CZ_NAME           TEXT,
    WFO               TEXT,
    BEGIN_DATE_TIME   TEXT,
    CZ_TIMEZONE       TEXT,
    END_DATE_TIME     TEXT,
    INJURIES_DIRECT   TEXT,
    INJURIES_INDIRECT TEXT,
    DEATHS_DIRECT     TEXT,
    DEATHS_INDIRECT   TEXT,
    DAMAGE_PROPERTY   TEXT,
    DAMAGE_CROPS      TEXT,
    SOURCE            TEXT,
    MAGNITUDE         TEXT,
    MAGNITUDE_TYPE    TEXT,
    FLOOD_CAUSE       TEXT,
    CATEGORY          TEXT,
    TOR_F_SCALE       TEXT,
    TOR_LENGTH        TEXT,
    TOR_WIDTH         TEXT,
    TOR_OTHER_WFO     TEXT,
    TOR_OTHER_CZ_STATE TEXT,
    TOR_OTHER_CZ_FIPS TEXT,
    TOR_OTHER_CZ_NAME TEXT,
    BEGIN_RANGE       TEXT,
    BEGIN_AZIMUTH     TEXT,
    BEGIN_LOCATION    TEXT,
    END_RANGE         TEXT,
    END_AZIMUTH       TEXT,
    END_LOCATION      TEXT,
    BEGIN_LAT         TEXT,
    BEGIN_LON         TEXT,
    END_LAT           TEXT,
    END_LON           TEXT,
    EPISODE_NARRATIVE TEXT,
    EVENT_NARRATIVE   TEXT,
    DATA_SOURCE       TEXT
);
